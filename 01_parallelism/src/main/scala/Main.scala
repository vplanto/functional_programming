// Імпорт бібліотеки для підтримки паралельних колекцій (додає метод .par до стандартних колекцій).
// Символ `._` у Scala означає імпорт УСІХ класів та методів із цього пакета (точний аналог `.*` у Java або С++).
import scala.collection.parallel.CollectionConverters._

// object означає створення "синглтону" — єдиного екземпляра об'єкта в усій програмі.
// extends App означає, що цей об'єкт є точкою входу в програму (аналог public static void main у Java або C++).
// Увесь код всередині цього об'єкта буде виконано при запуску програми.
object Main extends App {

  // def — ключове слово для визначення функції (методу).
  // transactionId: Double — вхідний параметр (у нашому випадку симулює ID транзакції або її суму).
  // : Double = { ... } — вказує, що функція повертає тип Double (оцінка ризику).
  def analyzeTransactionRisk(transactionId: Double): Double = {
    // var (variable) — це змінна, значення якої МОЖНА змінювати (мутувати) в процесі роботи.
    // У чистому функціональному програмуванні ми намагаємося уникати var, але всередині
    // локальних функцій для оптимізації швидкості обчислень це допускається (бо назовні ця зміна не витікає).
    var riskScore = transactionId
    
    // Звичайний цикл від 1 до 500. 
    // Символ `<-` (генератор) читається як "виймай елементи по черзі з правої частини і клади в ліву".
    // Символ `_` (підкреслення) означає, що сам номер ітерації нам не потрібен (ми його ігноруємо).
    for (_ <- 1 to 500) {
      // Симуляція важкої Machine Learning моделі (математичних матричних обчислень),
      // яка перевіряє транзакцію на ознаки шахрайства (Fraud Detection).
      riskScore = math.sin(riskScore) * math.cos(riskScore) + math.tan(riskScore % 1.0)
    }
    
    // В Scala не обов'язково писати слово "return". Останній обчислений вираз автоматично повертається з функції.
    riskScore
  }

  // println — стандартна функція для виведення тексту в консоль (Print Line). 
  // Вона доступна одразу, оскільки Scala автоматично імпортує базові функції з об'єкта scala.Predef.
  println("Генерація 1,000,000 елементів у пам'яті...")
  
  // val (value) — це "константа", значення якої НЕ МОЖНА змінити після створення (Immutable). 
  // У ФП ми пишемо 99% коду саме з використанням val, а не var.
  // (1 to 1000000) — створює діапазон чисел.
  // .map(_.toDouble) — перетворює кожне ціле число на Double.
  // .toVector — зберігає всі числа в колекцію Vector (це ефективний незмінний масив у Scala).
  val data = (1 to 1000000).map(_.toDouble).toVector

  println("\n=== 1. Синхронна обробка (1 ядро) ===")
  
  // System.currentTimeMillis() повертає поточний час у мілісекундах (вбудована функція з Java).
  val startSeq = System.currentTimeMillis()
  
  // Звичайний map обробляє масив послідовно: елемент за елементом на одному ядрі процесора.
  // .sum — зручний метод, який одразу сумує всі обчислені результати.
  val seqResult = data.map(analyzeTransactionRisk).sum
  
  // Рахуємо різницю між поточним часом і часом старту, щоб дізнатися, скільки тривало обчислення.
  val timeSeq = System.currentTimeMillis() - startSeq
  
  // s"..." (String interpolation) дозволяє вставляти значення змінних прямо в текст через знак долара $.
  println(s"Результат: $seqResult")
  println(s"Час виконання: $timeSeq мс")

  println("\n=== 2. Паралельна обробка (Всі ядра) ===")
  
  // Прогрів пулу потоків (необов'язково, але корисно для більш точних замірів).
  // Віртуальній машині JVM потрібен час на створення системних потоків.
  data.take(1000).par.map(analyzeTransactionRisk).sum 

  val startPar = System.currentTimeMillis()
  
  // Додавання .par перетворює наш звичайний незмінний Vector на паралельний ParVector.
  // Тепер метод .map автоматично розбиває дані на шматки і віддає їх усім доступним ядрам CPU одночасно.
  val parResult = data.par.map(analyzeTransactionRisk).sum
  
  val timePar = System.currentTimeMillis() - startPar
  println(s"Результат: $parResult")
  println(s"Час виконання: $timePar мс")
  
  // Рахуємо, у скільки разів паралельна версія відпрацювала швидше за синхронну.
  val speedup = timeSeq.toDouble / timePar
  
  // f"..." (форматований рядок) дозволяє вказати формат виведення чисел 
  // (наприклад, %.2f означає вивести лише 2 знаки після коми).
  println(f"\nПрискорення у ${speedup}%.2f разів!")
}
